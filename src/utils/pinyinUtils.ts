/**
 * 将输入的中文转为精简的大写拼音【首字母】组合
 * 例如: "系统管理查看权限" -> "XTGLCKQX"
 * 例如: "部门管理员" -> "BMGLY"
 */
export function convertToPinyinUpper(text?: string): string {
  if (!text || !text.trim()) return '';
  let result = '';
  for (const char of text.trim()) {
    if (/[a-zA-Z0-9]/.test(char)) {
      result += char.toUpperCase();
    } else if (FIRST_LETTER_MAP[char]) {
      result += FIRST_LETTER_MAP[char];
    }
  }
  return result;
}
